return function(h, loaded)
    local TrackerSort = loaded.ns.TrackerSort

    local function q(index, level, finished, onMap)
        return { index = index, level = level, finished = finished, onMap = onMap }
    end

    local function order(entries, tiers, zoneOnly, maxLevel)
        local out = {}
        for i, e in ipairs(TrackerSort.Order(entries, tiers, zoneOnly, maxLevel)) do
            out[i] = e.index
        end
        return table.concat(out, " ")
    end

    h.describe("TrackerSort.Tiers", function()
        h.it("all None is no tiers: the sort is off", function()
            h.eq(#TrackerSort.Tiers({ sortFirst = "none", sortSecond = "none", sortThird = "none" }), 0)
            h.eq(#TrackerSort.Tiers({}), 0)
        end)
        h.it("keeps the set tiers in slot order and skips None and junk", function()
            local tiers = TrackerSort.Tiers({ sortFirst = "zone", sortSecond = "none", sortThird = "level" })
            h.eq(table.concat(tiers, " "), "zone level")
            h.eq(#TrackerSort.Tiers({ sortFirst = "sideways" }), 0)
        end)
        h.it("is active with a tier set or Only this zone on, and not otherwise", function()
            h.falsy(TrackerSort.Active({ sortFirst = "none", zoneOnly = false }))
            h.truthy(TrackerSort.Active({ sortFirst = "level", zoneOnly = false }))
            h.truthy(TrackerSort.Active({ sortFirst = "none", zoneOnly = true }))
        end)
        h.it("is active with Hide quests above me set, and not at Off (0)", function()
            h.truthy(TrackerSort.Active({ sortFirst = "none", zoneOnly = false, hideAbove = 3 }))
            h.falsy(TrackerSort.Active({ sortFirst = "none", zoneOnly = false, hideAbove = 0 }))
        end)
        h.it("knows its three slots", function()
            h.truthy(TrackerSort.IsSlot("sortSecond"))
            h.falsy(TrackerSort.IsSlot("autoAccept"))
        end)
    end)

    h.describe("TrackerSort.HereSet", function()
        -- GetQuestsOnMap(1413) in the Crossroads, 2026-10-13: Stonetalon quests listed with mapID 1442.
        local pois = {
            { questID = 878, mapID = 1413 }, { questID = 95621, mapID = 1413 },
            { questID = 1060, mapID = 1442 }, { questID = 1483, mapID = 1442 },
        }
        h.it("holds the quests whose marker belongs to this map, not a neighbour's", function()
            local here = TrackerSort.HereSet(pois, 1413)
            h.eq(here[878], true)
            h.eq(here[95621], true)
            h.eq(here[1060], nil)
            h.eq(here[1483], nil)
        end)
        h.it("no map or no list is no answer; junk entries are skipped", function()
            h.eq(TrackerSort.HereSet(pois, nil), nil)
            h.eq(TrackerSort.HereSet(nil, 1413), nil)
            h.eq(next(TrackerSort.HereSet({ "junk", { mapID = 1413 } }, 1413)), nil)
        end)
    end)

    h.describe("TrackerSort.AutoTrackWrite", function()
        h.it("on: turns Blizzard's auto-track on when it is off or unknown, else leaves it", function()
            h.eq(TrackerSort.AutoTrackWrite(true, "0", false), "1")
            h.eq(TrackerSort.AutoTrackWrite(true, nil, false), "1")
            h.eq(TrackerSort.AutoTrackWrite(true, "1", false), nil)
        end)
        h.it("off and untouched: never writes, whatever the setting is", function()
            h.eq(TrackerSort.AutoTrackWrite(false, "0", false), nil)
            h.eq(TrackerSort.AutoTrackWrite(false, "1", false), nil)
        end)
        h.it("switched off: turns it off when it is on", function()
            h.eq(TrackerSort.AutoTrackWrite(false, "1", true), "0")
            h.eq(TrackerSort.AutoTrackWrite(false, "0", true), nil)
        end)
    end)

    h.describe("TrackerSort.Assign", function()
        h.it("taking a key another slot holds clears that slot to None", function()
            local c = TrackerSort.Assign({ sortFirst = "level", sortSecond = "none", sortThird = "zone" },
                "sortSecond", "level")
            h.eq(c.sortSecond, "level")
            h.eq(c.sortFirst, "none")
            h.eq(c.sortThird, nil)
        end)
        h.it("None never clears another slot", function()
            local c = TrackerSort.Assign({ sortFirst = "none", sortSecond = "level" }, "sortThird", "none")
            h.eq(c.sortThird, "none")
            h.eq(c.sortFirst, nil)
            h.eq(c.sortSecond, nil)
        end)
        h.it("re-picking a slot's own key changes nothing else", function()
            local c = TrackerSort.Assign({ sortFirst = "level" }, "sortFirst", "level")
            h.eq(c.sortFirst, "level")
            h.eq(c.sortSecond, nil)
        end)
    end)

    h.describe("TrackerSort.Less", function()
        h.it("level: lower first", function()
            h.truthy(TrackerSort.Less(q(2, 10), q(1, 12), { "level" }))
            h.falsy(TrackerSort.Less(q(1, 12), q(2, 10), { "level" }))
        end)
        h.it("level: an unknown level sorts after every known one", function()
            h.truthy(TrackerSort.Less(q(2, 60), q(1, nil), { "level" }))
            h.falsy(TrackerSort.Less(q(1, nil), q(2, 60), { "level" }))
            h.truthy(TrackerSort.Less(q(1, nil), q(2, nil), { "level" }))
        end)
        h.it("finished first; unknown counts as not finished", function()
            h.truthy(TrackerSort.Less(q(2, 10, true), q(1, 10, false), { "finished" }))
            h.truthy(TrackerSort.Less(q(2, 10, true), q(1, 10, nil), { "finished" }))
        end)
        h.it("this zone first; unknown counts as elsewhere", function()
            h.truthy(TrackerSort.Less(q(2, 10, false, true), q(1, 10, false, nil), { "zone" }))
        end)
        h.it("every tier tied: Blizzard's order", function()
            h.truthy(TrackerSort.Less(q(1, 10, true, true), q(2, 10, true, true), { "level", "finished", "zone" }))
            h.falsy(TrackerSort.Less(q(2, 10), q(1, 10), {}))
        end)
    end)

    h.describe("TrackerSort.Cap", function()
        h.it("is the player's level plus the slider, whole levels", function()
            h.eq(TrackerSort.Cap({ hideAbove = 3 }, 20), 23)
            h.eq(TrackerSort.Cap({ hideAbove = 3.0001 }, 20), 23)
        end)
        h.it("Off, or no level from the game, is no cap", function()
            h.eq(TrackerSort.Cap({ hideAbove = 0 }, 20), nil)
            h.eq(TrackerSort.Cap({}, 20), nil)
            h.eq(TrackerSort.Cap({ hideAbove = 3 }, nil), nil)
        end)
    end)

    h.describe("TrackerSort.Order", function()
        h.it("a cap drops quests above it, keeps one at it and one of unknown level", function()
            local entries = { q(1, 24), q(2, 23), q(3, nil), q(4, 10) }
            h.eq(order(entries, {}, false, 23), "2 3 4")
            h.eq(order(entries, {}, false, nil), "1 2 3 4")
        end)
        h.it("the cap and Only this zone both drop", function()
            h.eq(order({ q(1, 30, false, true), q(2, 10, false, false), q(3, 10, false, true) }, {}, true, 20), "3")
        end)
        h.it("steps down the tiers: this zone, then finished, then level", function()
            local entries = {
                q(1, 10, false, true), q(2, 12, true, true), q(3, 5, true, false),
                q(4, 3, false, false), q(5, 8, false, true),
            }
            h.eq(order(entries, { "zone", "finished", "level" }), "2 5 1 3 4")
        end)
        h.it("no tiers keeps Blizzard's order", function()
            h.eq(order({ q(1, 30), q(2, 10), q(3, 20) }, {}), "1 2 3")
        end)
        h.it("only this zone drops quests the game says are elsewhere, then sorts the rest", function()
            local entries = { q(1, 30, false, true), q(2, 10, false, false), q(3, 20, false, true) }
            h.eq(order(entries, { "level" }, true), "3 1")
            h.eq(order(entries, {}, true), "1 3")
        end)
        h.it("only this zone keeps a quest the game gave no answer for", function()
            h.eq(order({ q(1, 10, false, nil), q(2, 10, false, false) }, {}, true), "1")
        end)
        h.it("only this zone with nothing here is an empty list", function()
            h.eq(order({ q(1, 10, false, false) }, {}, true), "")
        end)
        h.it("returns a new list and leaves Blizzard's untouched", function()
            local entries = { q(1, 30), q(2, 10) }
            local sorted = TrackerSort.Order(entries, { "level" })
            h.eq(sorted[1].index, 2)
            h.eq(entries[1].index, 1)
        end)
    end)
end
